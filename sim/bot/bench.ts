// ============================================================
// Reproducible benchmark report.
//
//   npx tsx sim/bot/bench.ts [--quick] [--seed N] [--legacy6]
//
// Writes reports/bench-<date>.md and .json. Every number is produced by this
// script from fixed seeds; rerunning with the same seed and code reproduces it
// (wall-clock latencies aside). --legacy6 adds a 6-max match against the
// original engine (slow and memory hungry, so it is opt-in).
// ============================================================

import * as fs from 'fs';
import * as path from 'path';
import { parseCards, Rng, shuffledDeck } from '../../src/bot/cards';
import { multiwayEquity } from '../../src/bot/equity/equity';
import { evaluateHand } from '../../src/core/equity/hand-eval';
import { posterior } from '../../src/bot/opponents/profile';
import { fullRange, toWeighted, topRange } from '../../src/bot/ranges/range';
import { BotPolicy, botPolicy, POLICY_FACTORIES } from '../../src/bot/sim/policies';
import { bb100, pairedDiff, playSession, Policy } from '../../src/bot/sim/table';
import { makePolicy, pctl } from './run';

const has = (f: string) => process.argv.includes(`--${f}`);
const argN = (f: string, d: number) => { const i = process.argv.indexOf(`--${f}`); return i >= 0 ? Number(process.argv[i + 1]) : d; };
const quick = has('quick');
const seed = argN('seed', 2026);
const SAMPLES = 400;
const scale = quick ? 0.15 : 1;
const out: string[] = [];
const json: Record<string, unknown> = { seed, quick, samplesPerDecision: SAMPLES, node: process.version, date: new Date().toISOString() };
const say = (s = '') => { out.push(s); console.log(s); };
const fmt = (r: { bb100: number; ci95: number }) => `${r.bb100 >= 0 ? '+' : ''}${r.bb100.toFixed(1)} ± ${r.ci95.toFixed(1)}`;
const verdict = (r: { bb100: number; ci95: number }) => (r.bb100 - r.ci95 > 0 ? 'bot ahead' : r.bb100 + r.ci95 < 0 ? 'bot behind' : 'not significant');
const OPP = ['tight-aggressive', 'loose-passive', 'range-equity', 'loose-aggressive', 'tight-passive', 'calling-station', 'tight-aggressive', 'range-equity', 'loose-passive'];

async function session(specs: string[], hands: number, s: number, extra: Partial<Parameters<typeof playSession>[0]> = {}, policies?: Policy[]) {
  const players = specs.map((sp, i) => ({ playerId: `${sp}#${i}`, policy: policies?.[i] ?? makePolicy(sp, SAMPLES, s + i) }));
  const res = await playSession({ players, hands, seed: s, smallBlind: 10, bigBlind: 20, startStack: 2000, duplicate: true, ...extra });
  return { res, players };
}

async function main(): Promise<void> {
  const t0 = Date.now();
  say(`# Benchmark report`);
  say();
  say(`Generated by \`sim/bot/bench.ts\` on ${new Date().toISOString().slice(0, 10)}, seed ${seed}${quick ? ' (QUICK run: small samples, wide intervals)' : ''}, Node ${process.version}.`);
  say(`Bot Monte Carlo budget: ${SAMPLES} joint deals per postflop decision. Stacks 100bb, blinds 10/20, cash mode (stacks reset each hand).`);
  say(`Every table uses duplicate rotation: each deck is played once with the bot in every seat, and one deal (all rotations) is one sample for the confidence interval.`);
  say();

  // ---- 1. table sizes ----
  say(`## 1. Bot versus a mixed field, 2 to 10 players`);
  say();
  say(`| Players | Hands | Bot bb/100 (95% CI) | Verdict | Illegal actions |`);
  say(`|---|---|---|---|---|`);
  const sizes: unknown[] = [];
  for (let n = 2; n <= 10; n++) {
    const specs = ['bot', ...OPP.slice(0, n - 1)];
    const hands = Math.round((n <= 4 ? 6000 : 5400) * scale / n) * n;
    const { res, players } = await session(specs, hands, seed + n);
    const r = bb100(res.totals.get(players[0].playerId)!.perDeal);
    say(`| ${n} | ${res.hands} | ${fmt(r)} | ${verdict(r)} | ${res.illegal.length} |`);
    sizes.push({ players: n, hands: res.hands, ...r, illegal: res.illegal.length, field: specs.slice(1) });
  }
  json.tableSizes = sizes;
  say();
  say(`Field (in seat order, truncated to the table size): ${OPP.join(', ')}.`);
  say();

  // ---- 2. heads-up vs each benchmark ----
  say(`## 2. Heads-up versus each benchmark opponent`);
  say();
  say(`| Opponent | Family | Hands | Bot bb/100 (95% CI) | Verdict |`);
  say(`|---|---|---|---|---|`);
  const hu: unknown[] = [];
  const family: Record<string, string> = { random: 'independent', 'calling-station': 'independent (fixed strategy)', 'range-equity': 'independent (equity thresholds)', 'legacy-engine': 'independent (original repository engine, trained heads-up blueprint)' };
  for (const o of [...Object.keys(POLICY_FACTORIES).filter((k) => k !== 'bot'), 'legacy-engine']) {
    const hands = Math.round((o === 'legacy-engine' ? 10000 : 6000) * scale / 2) * 2;
    const { res, players } = await session(['bot', o], hands, seed + 100);
    const r = bb100(res.totals.get(players[0].playerId)!.perDeal);
    say(`| ${o} | ${family[o] ?? 'same model family as the bot\'s opponent model'} | ${res.hands} | ${fmt(r)} | ${verdict(r)} |`);
    hu.push({ opponent: o, hands: res.hands, ...r });
  }
  json.headsUp = hu;
  say();
  if (has('legacy6')) {
    const { res, players } = await session(['bot', ...Array(5).fill('legacy-engine')], Math.round(6000 * scale / 6) * 6, seed + 150);
    const r = bb100(res.totals.get(players[0].playerId)!.perDeal);
    say(`Six-max, bot versus five copies of the original engine: ${fmt(r)} bb/100 over ${res.hands} hands (${verdict(r)}).`);
    json.legacySixMax = { hands: res.hands, ...r };
  } else say(`Six-max versus the original engine was NOT run for this report (opt in with \`--legacy6\`).`);
  say();

  // ---- 3. paired comparison: opponent modelling on vs off ----
  say(`## 3. Does opponent modelling help? Paired comparison on identical deals`);
  say();
  const pairSpecs = ['loose-passive', 'tight-aggressive', 'calling-station', 'loose-aggressive', 'tight-passive'];
  const pairHands = Math.round(9000 * scale / 6) * 6;
  const a = await session(['bot', ...pairSpecs], pairHands, seed + 200);
  const b = await session(['bot-noexploit', ...pairSpecs], pairHands, seed + 200);
  const ra = bb100(a.res.totals.get(a.players[0].playerId)!.perDeal), rb = bb100(b.res.totals.get(b.players[0].playerId)!.perDeal);
  const diff = pairedDiff(a.res.totals.get(a.players[0].playerId)!.perDeal, b.res.totals.get(b.players[0].playerId)!.perDeal);
  say(`Same decks, same opponent seeds, six-handed, ${pairHands} hands each.`);
  say();
  say(`| Variant | bb/100 (95% CI) |`);
  say(`|---|---|`);
  say(`| With opponent profiles (exploitWeight 1) | ${fmt(ra)} |`);
  say(`| Without (exploitWeight 0) | ${fmt(rb)} |`);
  say(`| Paired difference | ${fmt(diff)} (${diff.bb100 - diff.ci95 > 0 ? 'profiles help' : diff.bb100 + diff.ci95 < 0 ? 'profiles hurt' : 'not significant'}) |`);
  json.exploitPaired = { with: ra, without: rb, diff, hands: pairHands };
  say();

  // ---- 4. tournaments ----
  say(`## 4. Tournament-style runs (stacks carry over, blinds double every 15 hands)`);
  say();
  const runs = quick ? 6 : 30;
  const places: number[] = [];
  for (let i = 0; i < runs; i++) {
    const specs = ['bot', 'tight-aggressive', 'loose-passive', 'range-equity', 'loose-aggressive', 'tight-passive'];
    const players = specs.map((sp, k) => ({ playerId: `${sp}#${k}`, policy: makePolicy(sp, SAMPLES, seed + i * 7 + k) }));
    const res = await playSession({
      players, hands: 5000, seed: seed + 300 + i, smallBlind: 10, bigBlind: 20, startStack: 1500, mode: 'tournament',
      levels: Array.from({ length: 14 }, (_, k) => ({ hands: 15, smallBlind: 10 * 2 ** k, bigBlind: 20 * 2 ** k })),
    });
    const idx = res.bustOrder.indexOf(players[0].playerId);
    places.push(idx < 0 ? 1 : 6 - idx);
  }
  const wins = places.filter((p) => p === 1).length;
  const se = Math.sqrt((wins / runs) * (1 - wins / runs) / runs);
  say(`${runs} six-player winner-take-all tournaments: the bot won ${wins} (${(100 * wins / runs).toFixed(0)}% ± ${(196 * se).toFixed(0)}%; an average player wins 16.7%). Mean finishing place ${(places.reduce((x, y) => x + y, 0) / runs).toFixed(2)} of 6.`);
  say(`The bot has no ICM or tournament-specific model: it plays chip EV. ${runs} tournaments is a small sample.`);
  json.tournaments = { runs, wins, places };
  say();

  // ---- 5. equity accuracy ----
  say(`## 5. Equity estimation error`);
  say();
  say(`Random spots (random hero hand, random flop/turn/river or preflop, 1 to 5 opponents holding the top 40% of hands or any two cards). Reference: ${quick ? "40,000" : "200,000"} samples (the reference has its own sampling error, which matters at the largest sample size).`);
  say();
  say(`| Samples | Spots | Mean abs error | Max abs error | Share of errors within 2 reported SE |`);
  say(`|---|---|---|---|---|`);
  const rng = new Rng(seed + 400);
  const spots = quick ? 12 : 60;
  const eqRows: unknown[] = [];
  const cases: { hero: [number, number]; board: number[]; n: number; wide: boolean; ref: number }[] = [];
  for (let i = 0; i < spots; i++) {
    const deck = shuffledDeck(rng);
    const hero: [number, number] = [deck[0], deck[1]];
    const board = deck.slice(2, 2 + [0, 3, 4, 5][i % 4]);
    const n = 1 + (i % 5), wide = i % 2 === 0;
    const range = toWeighted(wide ? fullRange() : topRange(0.4), [...hero, ...board]).range;
    const ref = multiwayEquity(hero, board, Array.from({ length: n }, () => range), quick ? 40000 : 200000, 9000 + i).equity;
    cases.push({ hero, board, n, wide, ref });
  }
  for (const samples of [400, 2000, 10000]) {
    let sum = 0, max = 0, within = 0;
    cases.forEach((c, i) => {
      const range = toWeighted(c.wide ? fullRange() : topRange(0.4), [...c.hero, ...c.board]).range;
      const e = multiwayEquity(c.hero, c.board, Array.from({ length: c.n }, () => range), samples, 500 + i);
      const err = Math.abs(e.equity - c.ref);
      sum += err; max = Math.max(max, err);
      if (err <= 2 * e.stdErr + 1e-9) within++;
    });
    say(`| ${samples} | ${cases.length} | ${(100 * sum / cases.length).toFixed(2)} pts | ${(100 * max).toFixed(2)} pts | ${(100 * within / cases.length).toFixed(0)}% |`);
    eqRows.push({ samples, meanAbs: sum / cases.length, max, within2se: within / cases.length });
  }
  json.equity = eqRows;
  say();

  // ---- 6. profiling accuracy ----
  say(`## 6. Opponent-profiling accuracy`);
  say();
  const bot = botPolicy({ samples: 200, seed });
  const truth = new Map<string, { vpip: number; pfr: number; opp: number }>();
  const profSpecs = ['tight-passive', 'loose-passive', 'tight-aggressive', 'loose-aggressive', 'range-equity'];
  const profHands = Math.round(3000 * scale);
  await playSession({
    players: [{ playerId: 'bot', policy: bot }, ...profSpecs.map((s) => ({ playerId: s, policy: makePolicy(s, SAMPLES, seed) }))],
    hands: profHands, seed: seed + 500, smallBlind: 10, bigBlind: 20, startStack: 2000,
    onHand: (r) => {
      for (const s of r.h.seats) {
        const acts = r.h.events.filter((e) => e.street === 'preflop' && e.seat === s.seat && !e.kind.startsWith('post'));
        if (!acts.some((e) => e.kind !== 'check')) continue;
        const t = truth.get(s.playerId) ?? { vpip: 0, pfr: 0, opp: 0 };
        t.opp++; if (acts.some((e) => e.kind === 'call' || e.kind === 'raise')) t.vpip++; if (acts.some((e) => e.kind === 'raise')) t.pfr++;
        truth.set(s.playerId, t);
      }
    },
  });
  say(`${profHands} six-handed hands. "Counted" is what the bot's profile recorded; "truth" is counted independently from the simulator's action log.`);
  say();
  say(`| Opponent | VPIP counted | VPIP truth | PFR counted | PFR truth | Posterior VPIP (90% interval) | Style label |`);
  say(`|---|---|---|---|---|---|---|`);
  const { classify, styleLabel } = await import('../../src/bot/opponents/profile');
  let mismatches = 0;
  for (const s of profSpecs) {
    const p = (bot as BotPolicy).agent.profiles.get(s)!, t = truth.get(s)!;
    if (p.stats.vpip.n !== t.vpip || p.stats.vpip.d !== t.opp || p.stats.pfr.n !== t.pfr) mismatches++;
    const q = posterior(p, 'vpip');
    say(`| ${s} | ${p.stats.vpip.n}/${p.stats.vpip.d} | ${t.vpip}/${t.opp} | ${p.stats.pfr.n}/${p.stats.pfr.d} | ${t.pfr}/${t.opp} | ${(100 * q.mean).toFixed(1)}% (${(100 * q.lo).toFixed(1)}–${(100 * q.hi).toFixed(1)}) | ${styleLabel(classify(p))} |`);
  }
  say();
  say(`Count mismatches between profile and ground truth: ${mismatches}.`);
  json.profiling = { hands: profHands, mismatches };
  say();

  // ---- 7. latency ----
  say(`## 7. Decision latency and raw speed (this machine)`);
  say();
  say(`| Players | MC samples | Decisions | p50 ms | p95 ms | max ms |`);
  say(`|---|---|---|---|---|---|`);
  const lat: unknown[] = [];
  for (const n of [2, 6, 10]) {
    for (const samples of [400, 2000, 8000]) {
      const pol = botPolicy({ samples, seed: 1 });
      const players = [{ playerId: 'bot', policy: pol as Policy }, ...OPP.slice(0, n - 1).map((s, i) => ({ playerId: `${s}${i}`, policy: makePolicy(s, SAMPLES, i) }))];
      const res = await playSession({ players, hands: Math.round(400 * scale) + 40, seed: seed + 600 + n, smallBlind: 10, bigBlind: 20, startStack: 2000 });
      const ms = res.latencyByPolicy.get('bot') ?? [];
      say(`| ${n} | ${samples} | ${ms.length} | ${pctl(ms, 50).toFixed(2)} | ${pctl(ms, 95).toFixed(2)} | ${Math.max(...ms).toFixed(1)} |`);
      lat.push({ players: n, samples, decisions: ms.length, p50: pctl(ms, 50), p95: pctl(ms, 95), max: Math.max(...ms) });
    }
  }
  json.latency = lat;
  const cards = parseCards('Ah Kd 7c 7d 2s Qh 9h');
  let acc = 0; const N = 2_000_000; const te = performance.now();
  for (let i = 0; i < N; i++) { cards[6] = 20 + (i % 20); acc += evaluateHand(cards); }
  const evalRate = N / ((performance.now() - te) / 1000);
  const hero: [number, number] = [cards[0], cards[1]];
  const any = toWeighted(fullRange(), hero).range;
  const tm = performance.now();
  multiwayEquity(hero, [], [any, any, any], 100000, 1);
  const eqRate = 100000 / ((performance.now() - tm) / 1000);
  say();
  say(`Seven-card evaluator: ${(evalRate / 1e6).toFixed(1)} million hands/s. Four-way preflop equity: ${(eqRate / 1000).toFixed(0)} thousand joint deals/s. (checksum ${acc % 997})`);
  say(`Latencies are for the simulator's synchronous path with a fixed sample count; the live extension uses the anytime path, which stops by the rules in src/bot/time/budget.ts.`);
  json.speed = { evalPerSec: evalRate, equityDealsPerSec: eqRate };
  say();
  say(`## How to read this`);
  say();
  say(`- A result whose interval contains zero is not evidence either way.`);
  say(`- The four archetype opponents are generated by the same behaviour model the bot uses to predict opponents, so results against them overstate real-world strength. The independent rows are the meaningful ones.`);
  say(`- Nothing here measures play against humans or against other competition bots, and no live PokerNow hand is included.`);
  say();
  say(`Total benchmark time: ${((Date.now() - t0) / 1000).toFixed(0)} s.`);

  const dir = path.resolve('reports');
  fs.mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().slice(0, 10) + (quick ? '-quick' : '');
  fs.writeFileSync(path.join(dir, `bench-${stamp}.md`), out.join('\n') + '\n');
  fs.writeFileSync(path.join(dir, `bench-${stamp}.json`), JSON.stringify(json, null, 2) + '\n');
  console.log(`\nwrote reports/bench-${stamp}.md and .json`);
}

main().catch((e) => { console.error(e); process.exit(1); });
