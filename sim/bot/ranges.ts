// ============================================================
// Strategy pack tool.
//
//   npm run bot:ranges -- validate <file>     check a pack (JSON, text or CSV) and print every issue
//   npm run bot:ranges -- import <file>       validate, then add it to src/bot/strategy/packs/ (bundled at the next build)
//   npm run bot:ranges -- remove <pack-id>    remove an imported pack
//   npm run bot:ranges -- list                packs and spots currently registered
//   npm run bot:ranges -- coverage            which preflop situations have data, per table size
//
// Packs are plain local files. Nothing is downloaded. A pack with any error is
// not imported. Formats: docs/bot/STRATEGY_LIBRARY.md.
// ============================================================

import * as fs from 'fs';
import * as path from 'path';
import { buildDefaultLibrary } from '../../src/bot/strategy/library/builtin';
import { importPack } from '../../src/bot/strategy/library/import';
import { StrategyLibrary } from '../../src/bot/strategy/library/library';
import { PreflopScenario, StrategyPack } from '../../src/bot/strategy/library/types';

const DIR = path.resolve('src/bot/strategy/packs');
const [cmd, arg] = process.argv.slice(2);

function writeIndex(): void {
  const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
  const names = files.map((_, i) => `p${i}`);
  const lines = [
    '// GENERATED by `npm run bot:ranges -- import ...` (sim/bot/ranges.ts). Do not edit by hand.',
    '//',
    '// Strategy packs imported by the user. They are bundled into the extension at',
    '// build time; nothing is downloaded at runtime. An empty list means only the',
    '// built-in chart packs are available.',
    "import type { StrategyPack } from '../library/types';",
    ...files.map((f, i) => `import ${names[i]} from './${f}';`),
    '',
    `export const USER_PACKS: StrategyPack[] = [${names.map((n) => `${n} as unknown as StrategyPack`).join(', ')}];`,
    '',
  ];
  fs.writeFileSync(path.join(DIR, 'index.ts'), lines.join('\n'));
}

function load(file: string): { pack: StrategyPack; ok: boolean } {
  const text = fs.readFileSync(file, 'utf8');
  let res;
  try { res = importPack(text, file.endsWith('.json') ? 'json' : file.endsWith('.csv') ? 'csv' : undefined); }
  catch (e) { console.error(`cannot read ${file}: ${(e as Error).message}`); process.exit(1); }
  for (const i of res.issues) console.log(`${i.level.toUpperCase().padEnd(7)} ${i.where}: ${i.message}`);
  const errors = res.issues.filter((i) => i.level === 'error').length;
  const p = res.pack;
  console.log(`${errors ? 'REJECTED' : 'OK'}: pack "${p.id}" (${p.name}), ${p.spots?.length ?? 0} spot(s), source ${p.source?.kind}${p.source?.verified ? ', verified' : ', NOT verified'}; ${errors} error(s), ${res.issues.length - errors} warning(s)`);
  return { pack: p, ok: errors === 0 };
}

function describe(lib: StrategyLibrary): void {
  for (const p of lib.packs) {
    const a = p.assumptions;
    console.log(`\n${p.id}  "${p.name}" rev ${p.revision}`);
    console.log(`  source: ${p.source.kind}${p.source.tool ? ` (${p.source.tool})` : ''}, ${p.source.verified ? 'verified' : 'NOT verified'}; licence: ${p.source.license ?? 'n/a'}`);
    console.log(`  assumes: ${a.format}, ${a.players} players, ${a.stackBB[0]}-${a.stackBB[1]}bb, ante ${a.anteBB ?? 0}bb; positions ${p.positions.join(' ')}`);
    const by = new Map<string, string[]>();
    for (const s of p.spots) by.set(s.scenario, [...(by.get(s.scenario) ?? []), s.villain ? `${s.hero}v${s.villain}` : s.hero]);
    for (const [sc, list] of by) console.log(`  ${sc.padEnd(13)} ${list.length} spot(s): ${list.join(' ')}`);
    if (p.references?.length) console.log(`  postflop references: ${p.references.length}`);
    if (p.principles?.length) console.log(`  principles: ${p.principles.length}`);
  }
}

function coverage(lib: StrategyLibrary): void {
  const scen: { s: PreflopScenario; villain: boolean; label: string }[] = [
    { s: 'rfi', villain: false, label: 'open raise (first in)' },
    { s: 'vs-limp', villain: false, label: 'facing limpers (isolate / over-limp)' },
    { s: 'bb-vs-limp', villain: false, label: 'big blind option after limpers' },
    { s: 'vs-open', villain: true, label: 'facing an open (call / 3-bet)' },
    { s: 'vs-open-call', villain: true, label: 'open plus caller(s) (overcall / squeeze)' },
    { s: 'vs-3bet', villain: true, label: 'opened, facing a 3-bet' },
    { s: 'vs-squeeze', villain: true, label: 'facing a squeeze' },
    { s: 'vs-4bet', villain: true, label: '3-bet, facing a 4-bet' },
    { s: 'cold-4bet', villain: true, label: 'facing a raise and a 3-bet cold' },
    { s: 'push-fold', villain: false, label: 'short-stack push or fold' },
  ];
  console.log('Share of (hero seat, villain seat) combinations with data at 100bb, cash, no ante. E = exact match, a = approximation, . = none.\n');
  console.log('situation'.padEnd(42) + [2, 3, 4, 5, 6, 7, 8, 9, 10].map((n) => `${n}p`.padStart(9)).join(''));
  for (const sc of scen) {
    let row = sc.label.padEnd(42);
    for (let n = 2; n <= 10; n++) {
      let total = 0, exact = 0, approx = 0;
      for (let hb = 0; hb < n; hb++) {
        const vs = sc.villain ? Array.from({ length: n }, (_, v) => v).filter((v) => v !== hb) : [undefined];
        for (const vb of vs) {
          // Only orderings that can happen: a caller or 3-bettor of an open acts after the opener; the blinds can always respond.
          if (sc.s === 'rfi' && hb === 0) continue;
          if (sc.s === 'bb-vs-limp' && hb !== 0) continue;
          if (sc.s === 'vs-limp' && (hb === 0 || hb === n - 1)) continue;
          if ((sc.s === 'vs-open' || sc.s === 'vs-open-call' || sc.s === 'cold-4bet') && vb !== undefined && vb < hb) continue;
          if (sc.s === 'vs-3bet' && vb !== undefined && vb > hb) continue;   // the 3-bettor acts after the opener
          total++;
          const m = lib.find({ scenario: sc.s, players: n, heroBehind: hb, villainBehind: vb, effStackBB: sc.s === 'push-fold' ? 10 : 100, anteBB: 0, callers: sc.s === 'vs-open-call' || sc.s === 'vs-squeeze' ? 1 : 0, limpers: sc.s.includes('limp') ? 1 : 0 });
          if (m) { if (m.quality === 'exact') exact++; else approx++; }
        }
      }
      row += (total === 0 ? '-' : `${exact ? `E${Math.round((100 * exact) / total)}` : ''}${approx ? `a${Math.round((100 * approx) / total)}` : ''}${!exact && !approx ? '.' : ''}`).padStart(9);
    }
    console.log(row);
  }
  console.log('\nAnything not covered is played by the percentile heuristics and labelled "heuristic" in the decision.');
}

if (cmd === 'validate' && arg) process.exit(load(arg).ok ? 0 : 1);
else if (cmd === 'import' && arg) {
  const { pack, ok } = load(arg);
  if (!ok) process.exit(1);
  const { library } = buildDefaultLibrary();
  if (library.packs.some((p) => p.id === pack.id) && !fs.existsSync(path.join(DIR, `${pack.id}.json`))) { console.error(`a built-in pack already uses the id "${pack.id}"`); process.exit(1); }
  fs.writeFileSync(path.join(DIR, `${pack.id}.json`), JSON.stringify(pack, null, 1) + '\n');
  writeIndex();
  console.log(`imported to src/bot/strategy/packs/${pack.id}.json. Run "npm run build" and reload the extension to use it.`);
} else if (cmd === 'remove' && arg) {
  const f = path.join(DIR, `${arg}.json`);
  if (!fs.existsSync(f)) { console.error(`no imported pack "${arg}"`); process.exit(1); }
  fs.unlinkSync(f);
  writeIndex();
  console.log(`removed ${arg}`);
} else if (cmd === 'list' || cmd === 'coverage') {
  const { library, rejected } = buildDefaultLibrary();
  for (const r of rejected) console.log(`REJECTED pack ${r.id}: ${r.errors.join('; ')}`);
  if (cmd === 'list') describe(library); else coverage(library);
} else {
  console.error('usage: ranges validate <file> | import <file> | remove <pack-id> | list | coverage');
  process.exit(2);
}
