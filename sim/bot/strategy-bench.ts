// ============================================================
// Baseline (version 1, the engine at 0.5.1) versus current (version 2) strategy benchmark.
//
//   npm run bot:strategy-bench [-- --quick] [--seed N]
//
// Writes reports/strategy-bench-<date>.md and .json. Every table plays the SAME decks, seats and opponent
// seeds once with the v2 bot and once with the v1 bot in the measured seat; "difference" is the paired
// per-deal difference, which is far less noisy than either number. Duplicate rotation: each deck is played
// with the bot in every seat, and one deal (all rotations) is one sample for the confidence interval.
//
// The default seed (2027) was not used while the engine was being changed (pilot runs used 11, 21 and 31).
// ============================================================

import * as fs from 'fs';
import * as path from 'path';
import { bb100, pairedDiff, playSession, Policy } from '../../src/bot/sim/table';
import { makePolicy, pctl } from './run';
import { runScenarios } from './scenarios';

const has = (f: string) => process.argv.includes(`--${f}`);
const argN = (f: string, d: number) => { const i = process.argv.indexOf(`--${f}`); return i >= 0 ? Number(process.argv[i + 1]) : d; };
const quick = has('quick');
const seed = argN('seed', 2027);
const scale = quick ? 0.12 : 1;
const SAMPLES = 400;
const out: string[] = [];
const json: Record<string, unknown> = { seed, quick, samplesPerDecision: SAMPLES, node: process.version, date: new Date().toISOString() };
const say = (s = '') => { out.push(s); console.log(s); };
const fmt = (r: { bb100: number; ci95: number }) => `${r.bb100 >= 0 ? '+' : ''}${r.bb100.toFixed(1)} ± ${r.ci95.toFixed(1)}`;
const verdict = (r: { bb100: number; ci95: number }) => (r.bb100 - r.ci95 > 0 ? 'v2 ahead' : r.bb100 + r.ci95 < 0 ? 'v2 behind' : 'no significant difference');

interface Run { perDeal: number[]; illegal: number; ms: number[]; flop: { hu: number[]; multi: number[] } }

async function run(hero: string, field: string[], hands: number, s: number): Promise<Run> {
  const specs = [hero, ...field];
  const players = specs.map((sp, i) => ({ playerId: `${i}`, policy: makePolicy(sp, SAMPLES, s + i) as Policy }));
  const flop = { hu: [] as number[], multi: [] as number[] };
  const res = await playSession({
    players, hands, seed: s, smallBlind: 10, bigBlind: 20, startStack: 2000, duplicate: true,
    onHand: (r) => {
      // Net of the measured player in hands where it saw a flop, split by how many players saw it.
      const seat = r.h.seats.find((x) => x.playerId === '0');
      if (!seat) return;
      const sawFlop = (x: { seat: number }) => !r.h.events.some((e) => e.street === 'preflop' && e.kind === 'fold' && e.seat === x.seat);
      if (r.h.board.length < 3 || !sawFlop(seat)) return;
      const n = r.h.seats.filter((x) => x.dealtIn && sawFlop(x)).length;
      (n === 2 ? flop.hu : flop.multi).push((r.nets.get(seat.seat) ?? 0) / r.h.bigBlind);
    },
  });
  return { perDeal: res.totals.get('0')!.perDeal, illegal: res.illegal.length, ms: res.latencyByPolicy.get(players[0].policy.name) ?? [], flop };
}

const mean = (xs: number[]) => { const r = bb100(xs); return { mean: r.bb100 / 100, ci: r.ci95 / 100, n: xs.length }; };

async function main(): Promise<void> {
  const t0 = Date.now();
  say(`# Strategy benchmark: version 2 against the version 1 baseline`);
  say();
  say(`Generated by \`sim/bot/strategy-bench.ts\` on ${new Date().toISOString().slice(0, 10)}, seed ${seed}${quick ? ' (QUICK run: small samples, wide intervals)' : ''}, Node ${process.version}.`);
  say(`Version 1 is the strategy engine exactly as released in 0.5.1 (\`engine: 'v1'\`). Version 2 is the current engine.`);
  say(`${SAMPLES} Monte Carlo deals per postflop decision, 100bb stacks, blinds 10/20, cash mode, duplicate rotation. All figures are big blinds per 100 hands with a 95% confidence interval.`);
  say(`Seed ${seed} was not used during development; pilot runs used other seeds.`);
  say();

  const A = 'tight-aggressive', LP = 'loose-passive', RE = 'range-equity', LA = 'loose-aggressive', TP = 'tight-passive', CS = 'calling-station', RA = 'range-aware';
  const fields: { name: string; family: string; field: string[]; hands: number }[] = [
    { name: 'Six-handed, mixed archetypes', family: 'v1 model family (4 of 5), 1 independent', field: [A, LP, RE, LA, TP], hands: 12000 },
    { name: 'Six-handed, independent only', family: 'independent', field: [RE, CS, RE, 'random', RE], hands: 12000 },
    { name: 'Six-handed, range-aware opponents', family: 'v2 model family', field: [RA, RA, RA, RA, RA], hands: 9000 },
    { name: 'Six-handed, everything mixed', family: 'mixed', field: [RA, A, RE, LP, RA], hands: 12000 },
    { name: 'Nine-handed, mixed', family: 'mixed', field: [A, LP, RE, RA, TP, CS, RA, RE], hands: 9000 },
    { name: 'Three-handed, mixed', family: 'mixed', field: [RA, RE], hands: 9000 },
    { name: 'Heads-up vs range-equity', family: 'independent', field: [RE], hands: 10000 },
    { name: 'Heads-up vs range-aware', family: 'v2 model family', field: [RA], hands: 10000 },
    { name: 'Heads-up vs tight-aggressive', family: 'v1 model family', field: [A], hands: 10000 },
    { name: 'Heads-up vs the original repository engine', family: 'independent (trained heads-up)', field: ['legacy-engine'], hands: 6000 },
  ];

  say(`## 1. Same seat, same decks, same opponents: v2 versus v1`);
  say();
  say(`| Table | Opponent family | Hands | v2 bb/100 | v1 bb/100 | Paired difference (v2 − v1) | Verdict | Illegal actions (v2 / v1) |`);
  say(`|---|---|---|---|---|---|---|---|`);
  const rows: unknown[] = [];
  const lat: Record<string, number[]> = { v2: [], v1: [] };
  const flopAgg = { v2: { hu: [] as number[], multi: [] as number[] }, v1: { hu: [] as number[], multi: [] as number[] } };
  let i = 0;
  for (const f of fields) {
    const n = f.field.length + 1;
    const hands = Math.max(n * 20, Math.round((f.hands * scale) / n) * n);
    const s = seed + 1000 * ++i;
    const a = await run('bot', f.field, hands, s), b = await run('bot-v1', f.field, hands, s);
    const ra = bb100(a.perDeal), rb = bb100(b.perDeal), d = pairedDiff(a.perDeal, b.perDeal);
    say(`| ${f.name} | ${f.family} | ${hands} | ${fmt(ra)} | ${fmt(rb)} | ${fmt(d)} | ${verdict(d)} | ${a.illegal} / ${b.illegal} |`);
    rows.push({ ...f, hands, v2: ra, v1: rb, diff: d });
    if (n >= 3) { lat.v2.push(...a.ms); lat.v1.push(...b.ms); for (const k of ['hu', 'multi'] as const) { flopAgg.v2[k].push(...a.flop[k]); flopAgg.v1[k].push(...b.flop[k]); } }
  }
  json.paired = rows;
  say();
  say(`"v1 model family": the four archetype opponents choose their actions with the same behaviour model version 1 uses to predict opponents, so version 1 predicts them almost perfectly. "v2 model family": the range-aware opponent does the same for version 2. Only the independent rows are neutral.`);
  say();

  say(`## 2. Both engines at one table`);
  say();
  {
    const hands = Math.round((12000 * scale) / 6) * 6;
    const specs = ['bot', 'bot-v1', 'bot', 'bot-v1', 'bot', 'bot-v1'];
    const players = specs.map((sp, k) => ({ playerId: `${sp}#${k}`, policy: makePolicy(sp, SAMPLES, seed + 50 + k) as Policy }));
    const res = await playSession({ players, hands, seed: seed + 50, smallBlind: 10, bigBlind: 20, startStack: 2000, duplicate: true });
    const sum = (tag: string) => { const per = players.filter((p) => p.playerId.startsWith(`${tag}#`)).map((p) => res.totals.get(p.playerId)!.perDeal); return per[0].map((_, k) => (per[0][k] + per[1][k] + per[2][k]) / 3); };
    const v2 = bb100(sum('bot')), v1 = bb100(sum('bot-v1'));
    say(`Three v2 seats and three v1 seats, alternating, ${hands} hands. Average v2 seat: ${fmt(v2)} bb/100. Average v1 seat: ${fmt(v1)} bb/100 (the two sum to zero). ${v2.bb100 - v2.ci95 > 0 ? 'v2 ahead.' : v2.bb100 + v2.ci95 < 0 ? 'v2 behind.' : 'No significant difference.'}`);
    json.direct = { hands, v2, v1 };
  }
  say();

  say(`## 3. Heads-up and multiway pots after the flop`);
  say();
  say(`All ring tables of section 1 pooled; hands in which the measured seat saw a flop, by the number of players who saw it. Mean result of the hand in big blinds (not per 100). These are not paired and the two engines do not reach exactly the same flops.`);
  say();
  say(`| Flop seen by | v2: hands | v2: bb per hand | v1: hands | v1: bb per hand |`);
  say(`|---|---|---|---|---|`);
  for (const k of ['hu', 'multi'] as const) {
    const a = mean(flopAgg.v2[k]), b = mean(flopAgg.v1[k]);
    say(`| ${k === 'hu' ? 'two players' : 'three or more'} | ${a.n} | ${a.mean.toFixed(2)} ± ${a.ci.toFixed(2)} | ${b.n} | ${b.mean.toFixed(2)} ± ${b.ci.toFixed(2)} |`);
  }
  json.flops = { v2: { hu: mean(flopAgg.v2.hu), multi: mean(flopAgg.v2.multi) }, v1: { hu: mean(flopAgg.v1.hu), multi: mean(flopAgg.v1.multi) } };
  say();

  say(`## 4. Off-strategy play: Hero ignores preflop fold advice`);
  say();
  {
    const field = [RA, A, RE, LP, RA];
    const hands = Math.round((12000 * scale) / 6) * 6;
    const a = await run('bot-deviating', field, hands, seed + 70), b = await run('bot-v1-deviating', field, hands, seed + 70);
    const d = pairedDiff(a.perDeal, b.perDeal);
    say(`Six-handed mixed table, ${hands} hands. In both runs the measured seat calls half of the cheap preflop bets (5bb or less) that its engine wanted to fold, then lets the engine play the hand. Both lose chips doing this; the question is which engine handles the resulting hands better.`);
    say();
    say(`| Engine | bb/100 |`);
    say(`|---|---|`);
    say(`| v2 with forced loose calls | ${fmt(bb100(a.perDeal))} |`);
    say(`| v1 with forced loose calls | ${fmt(bb100(b.perDeal))} |`);
    say(`| Paired difference | ${fmt(d)} (${verdict(d)}) |`);
    json.deviating = { hands, v2: bb100(a.perDeal), v1: bb100(b.perDeal), diff: d };
  }
  say();

  say(`## 5. Wrong opponent assumptions`);
  say();
  {
    const field = [CS, 'random', CS, 'random', LP];
    const hands = Math.round((9000 * scale) / 6) * 6;
    const a = await run('bot-noexploit', field, hands, seed + 90), b = await run('bot-v1-noexploit', field, hands, seed + 90);
    const c = await run('bot', field, hands, seed + 90);
    const d = pairedDiff(a.perDeal, b.perDeal);
    say(`Six-handed against two calling stations, two random players and a loose-passive player, ${hands} hands: opponents who do not behave like either engine's model. Opponent statistics switched off, so neither engine can correct its assumptions.`);
    say();
    say(`| Engine | bb/100 |`);
    say(`|---|---|`);
    say(`| v2, statistics off | ${fmt(bb100(a.perDeal))} |`);
    say(`| v1, statistics off | ${fmt(bb100(b.perDeal))} |`);
    say(`| Paired difference | ${fmt(d)} (${verdict(d)}) |`);
    say(`| v2, statistics on (for reference) | ${fmt(bb100(c.perDeal))} |`);
    json.misspecified = { hands, v2: bb100(a.perDeal), v1: bb100(b.perDeal), diff: d, v2WithStats: bb100(c.perDeal) };
  }
  say();

  say(`## 6. Decision scenarios`);
  say();
  {
    const count = (rs: ReturnType<typeof runScenarios>, set: string) => { const cs = rs.filter((r) => r.scenario.set === set).flatMap((r) => r.checks.filter((c) => c.kind === 'property')); return `${cs.filter((c) => c.pass).length} of ${cs.length}`; };
    const r1 = runScenarios('v1', 3000), r2 = runScenarios('v2', 3000);
    say(`| Set | Scenarios | v1 properties holding | v2 properties holding |`);
    say(`|---|---|---|---|`);
    for (const set of ['design', 'held-out']) say(`| ${set} | ${r2.filter((r) => r.scenario.set === set).length} | ${count(r1, set)} | ${count(r2, set)} |`);
    say();
    say(`Properties are statements that follow from the rules or the engine's stated model (see \`sim/bot/scenarios.ts\`). Full table: \`npm run bot:scenarios\`.`);
    say(`Solver-reference comparison: not available. No authorised solver output has been imported, so there is no measurement of decision quality against solver play.`);
    json.scenarios = { v1: { design: count(r1, 'design'), heldOut: count(r1, 'held-out') }, v2: { design: count(r2, 'design'), heldOut: count(r2, 'held-out') } };
  }
  say();

  say(`## 7. Decision time (simulator path, ${SAMPLES} deals, ring tables of section 1)`);
  say();
  say(`| Engine | Decisions | p50 ms | p95 ms | max ms |`);
  say(`|---|---|---|---|---|`);
  for (const k of ['v2', 'v1'] as const) say(`| ${k} | ${lat[k].length} | ${pctl(lat[k], 50).toFixed(2)} | ${pctl(lat[k], 95).toFixed(1)} | ${Math.max(0, ...lat[k]).toFixed(0)} |`);
  json.latency = { v2: { p50: pctl(lat.v2, 50), p95: pctl(lat.v2, 95), max: Math.max(0, ...lat.v2) }, v1: { p50: pctl(lat.v1, 50), p95: pctl(lat.v1, 95), max: Math.max(0, ...lat.v1) } };
  say();
  say(`## How to read this`);
  say();
  say(`- An interval that contains zero is not evidence either way.`);
  say(`- Every opponent here is a program. Nothing measures play against people or against other competition bots, and no solver reference is included.`);
  say(`- The simulated opponents do not punish the things version 2 was changed to avoid (for example, none of the v1-family opponents attacks a weak lead), so a simulation can understate or overstate the effect of those changes at a real table.`);
  say();
  say(`Total time: ${((Date.now() - t0) / 1000).toFixed(0)} s.`);

  const dir = path.resolve('reports');
  fs.mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().slice(0, 10) + (quick ? '-quick' : '');
  fs.writeFileSync(path.join(dir, `strategy-bench-${stamp}.md`), out.join('\n') + '\n');
  fs.writeFileSync(path.join(dir, `strategy-bench-${stamp}.json`), JSON.stringify(json, null, 2) + '\n');
  console.log(`\nwrote reports/strategy-bench-${stamp}.md and .json`);
}

main().catch((e) => { console.error(e); process.exit(1); });
